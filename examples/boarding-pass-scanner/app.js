  function imageToDsImageData(img) {
    var width = img.naturalWidth || img.width;
    var height = img.naturalHeight || img.height;
    if (width > MAX_IMAGE_WIDTH) {
      height = Math.round(height * MAX_IMAGE_WIDTH / width);
      width = MAX_IMAGE_WIDTH;
    }

    var canvas = document.createElement('canvas');
    canvas.width = width;
    canvas.height = height;
    var ctx = canvas.getContext('2d', { willReadFrequently: true });
    /* Composite onto white before drawing. A PNG may carry an alpha channel —
       anything exported from a canvas usually does — and a transparent pixel
       drawn onto a blank canvas stays (0,0,0,0). Passed to the SDK as RGBA that
       reads as black, so the quiet zone becomes ink and the symbol disappears. */
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(0, 0, width, height);
    ctx.drawImage(img, 0, 0, width, height);

    var pixels = ctx.getImageData(0, 0, width, height);
    /* This is exactly the shape CaptureVisionRouter.capture() expects: an RGBA
       buffer straight out of getImageData(), stride 4 x width, format 10
       (IPF_ABGR_8888). A Blob or canvas takes a different internal path and
       silently returns no results. */
    return {
      bytes: new Uint8Array(pixels.data.buffer, pixels.data.byteOffset, pixels.data.length),
      width: width,
      height: height,
      stride: 4 * width,
      format: 10
    };
  }

  function loadImageElement(src) {
    return new Promise(function (resolve, reject) {
      var img = new Image();
      img.onload = function () { resolve(img); };
      img.onerror = function () { reject(new Error('The image could not be decoded.')); };
      img.src = src;
    });
  }

  function barcodeItemsFrom(result) {
    if (!result) return [];
    if (result.barcodeResultItems && result.barcodeResultItems.length) return result.barcodeResultItems;
    return (result.items || []).filter(function (item) {
      return item.type === Dynamsoft.Core.EnumCapturedResultItemType.CRIT_BARCODE;
    });
  }

  function decodeImage(src) {
    return loadImageElement(src).then(function (img) {
      return applySettings().then(function () {
        return cvRouter.capture(imageToDsImageData(img), PRESET_TEMPLATE);
      });
    }).then(barcodeItemsFrom);
  }

  function scanImageSource(src, source) {
    if (!state.sdkReady) {
      showTip('The scanner is still starting. Try again in a moment.', true);
      return;
    }
    if (state.decodeBusy) return;

    state.decodeBusy = true;
    showTip('Reading the image…');
    return feedback.run('Decoding the barcode…', function () {
      return decodeImage(src);
    }).then(function (items) {
      if (!items.length) {
        analytics.fail(source, 'none');
        showTip('No barcode was found in that image. Try a larger or sharper crop of the barcode.', true);
        return;
      }
      showResults(items, source, src);
    }).catch(function (error) {
      console.error(error);
      analytics.error('image_decode_failed', String((error && error.message) || error).slice(0, 120));
      showTip('That image could not be read: ' + ((error && error.message) || error), true);
    }).then(function () {
      state.decodeBusy = false;
    });
  }

  function handleImageFile(file) {
    if (!file) return;
    if (!/^image\//.test(file.type)) {
      showTip('That file is not an image. Upload a PNG, JPG, BMP or WebP picture of a boarding pass barcode.', true);
      return;
    }
    analytics.action('image_load', { type: file.type, size: file.size });
    readAsDataURL(file).then(function (src) {
      return scanImageSource(src, 'upload');
    }).catch(function (error) {
      console.error(error);
      showTip('That file could not be read.', true);
    });
  }

  function readAsDataURL(file) {
    return new Promise(function (resolve, reject) {
      var reader = new FileReader();
      reader.onload = function (event) { resolve(event.target.result); };
      reader.onerror = function () { reject(new Error('The file could not be read.')); };
      reader.readAsDataURL(file);
    });
  }

  function imageFromClipboard(event) {
    var data = event.clipboardData || window.clipboardData;
    if (!data) return null;
    if (data.files && data.files.length) {
      for (var i = 0; i < data.files.length; i++) {
        if (/^image\//.test(data.files[i].type)) return data.files[i];
      }
    }
    if (data.items) {
      for (var j = 0; j < data.items.length; j++) {
        if (/^image\//.test(data.items[j].type)) {
          var file = data.items[j].getAsFile();
          if (file) return file;
        }
      }
    }
    return null;
  }

