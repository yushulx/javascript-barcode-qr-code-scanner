  /* The format mask spans more than 32 bits, so this SDK build exposes the enum
     values as BigInt. A plain `var mask = 0` throws "Cannot mix BigInt and other
     types" on the first `|=`, which is why the accumulator starts at 0n. */
  function scopeMask() {
    var table = formatEnum();
    if (!table) return null;

    if (state.scope === 'all') return table.BF_ALL === undefined ? null : table.BF_ALL;

    var names = state.scope === 'boarding' ? BOARDING_FORMATS : ALL_2D_FORMATS;
    var mask = 0n;
    var missing = [];
    names.forEach(function (name) {
      if (table[name] === undefined) {
        missing.push(name);
        return;
      }
      mask |= table[name];
    });
    if (missing.length) console.warn('Barcode formats missing from this SDK build:', missing);
    return mask || null;
  }

  function applySettings(force) {
    if (!state.sdkReady && !force) return Promise.resolve();
    if (!cvRouter) return Promise.resolve();
    if (!force && state.configuredScope === state.scope) return Promise.resolve();

    return cvRouter.getSimplifiedSettings(PRESET_TEMPLATE).then(function (settings) {
      var mask;
      try {
        mask = scopeMask();
      } catch (error) {
        /* Narrowing the symbologies is an optimisation, not a requirement. If
           the mask cannot be built, scan with the preset's own default rather
           than failing to start. */
        console.warn('Could not build the format mask; using the preset default:', error);
        mask = null;
      }
      if (mask !== null) settings.barcodeSettings.barcodeFormatIds = mask;
      return cvRouter.updateSettings(PRESET_TEMPLATE, settings);
    }).then(function () {
      state.configuredScope = state.scope;
    });
  }

