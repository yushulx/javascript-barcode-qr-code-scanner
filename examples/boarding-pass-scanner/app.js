  /* The visual summary: what the pass says, arranged the way a pass is. */
  function passCard(decoded) {
    var card = el('div', 'pass-card');

    var head = el('div', 'pass-head');
    head.appendChild(el('span', 'pass-airline', decoded.carrierName || decoded.carrier));
    head.appendChild(el('span', 'pass-class', decoded.legs[0].compartmentLabel || ''));
    card.appendChild(head);

    var route = el('div', 'pass-route');
    route.appendChild(routeEnd(decoded.legs[0].from, decoded.legs[0].fromCity));
    route.appendChild(el('span', 'pass-arrow', '\u2192'));
    route.appendChild(routeEnd(decoded.legs[0].to, decoded.legs[0].toCity));
    card.appendChild(route);

    var facts = el('div', 'pass-facts');
    [
      ['Passenger', decoded.passengerName],
      ['PNR', decoded.pnr],
      ['Flight', decoded.carrier + ' ' + decoded.flightNumber],
      ['Date', decoded.legs[0].flightDateLabel || decoded.legs[0].julianDate],
      ['Seat', decoded.legs[0].seat || 'unassigned'],
      ['Sequence', decoded.sequence],
      ['Status', decoded.passengerStatus
        + (decoded.passengerStatusLabel ? ' \u00b7 ' + decoded.passengerStatusLabel : '')],
      ['Symbology', 'BCBP ' + (decoded.version === null ? 'v0 (no version field)' : 'v' + decoded.version)]
    ].forEach(function (pair) {
      var fact = el('div', 'pass-fact');
      fact.appendChild(el('span', 'pass-fact-label', pair[0]));
      fact.appendChild(el('span', 'pass-fact-value', pair[1]));
      facts.appendChild(fact);
    });
    card.appendChild(facts);

    if (decoded.legs.length > 1) {
      var list = el('div', 'pass-legs');
      decoded.legs.forEach(function (leg) {
        list.appendChild(el('div', 'pass-leg', 'Leg ' + leg.index + '  \u00b7  ' + leg.from + ' \u2192 ' + leg.to
          + '  \u00b7  ' + leg.carrier + ' ' + leg.flightNumber + '  \u00b7  '
          + (leg.flightDateLabel || leg.julianDate) + '  \u00b7  seat ' + (leg.seat || 'unassigned')));
      });
      card.appendChild(list);
    }

    return card;
  }

