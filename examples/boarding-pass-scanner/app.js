  /* A flat JSON view of the parse, which is what most callers actually want to
     pipe into the rest of their application. */
  function toJson(decoded) {
    return {
      format: 'BCBP',
      version: decoded.version,
      passenger: {
        name: decoded.passengerName,
        surname: decoded.surname,
        givenNames: decoded.givenNames,
        pnr: decoded.pnr,
        status: decoded.passengerStatus,
        statusLabel: decoded.passengerStatusLabel,
        electronicTicket: decoded.electronicTicket
      },
      legs: decoded.legs.map(function (leg) {
        return {
          index: leg.index,
          from: leg.from,
          fromCity: leg.fromCity,
          to: leg.to,
          toCity: leg.toCity,
          carrier: leg.carrier,
          carrierName: leg.carrierName,
          flightNumber: leg.flightNumber,
          julianDate: leg.julianDate,
          flightDate: leg.flightDate,
          compartment: leg.compartment,
          compartmentLabel: leg.compartmentLabel,
          seat: leg.seat,
          sequence: leg.sequence,
          pnr: leg.pnr
        };
      }),
      optional: decoded.unique.concat(decoded.legs.reduce(function (acc, leg) {
        return acc.concat(leg.fields);
      }, [])).filter(function (field) {
        return field.value !== '';
      }).map(function (field) {
        return {
          item: field.item,
          code: field.code,
          label: field.label,
          value: field.value,
          meaning: field.meaning || undefined,
          offset: field.offset + 1
        };
      }),
      security: decoded.security || undefined,
      signature: state.lastSignature || undefined,
      checks: decoded.checks,
      warnings: decoded.warnings,
      payload: decoded.raw
    };
  }

